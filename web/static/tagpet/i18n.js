document.addEventListener('alpine:init', () => {
    const stored = localStorage.getItem('lang');
    const auto = navigator.language.startsWith('en') ? 'en' : 'pt-BR';
    const initial = stored || auto;
    document.documentElement.lang = initial;

    Alpine.store('i18n', {
        current: initial,
        t(key) {
            return translations[this.current]?.[key] ?? translations['pt-BR']?.[key] ?? key;
        },
        set(lang) {
            this.current = lang;
            localStorage.setItem('lang', lang);
            document.documentElement.lang = lang;
        }
    });

    window.NOGRAU_NAV = {
        t: (key) => Alpine.store('i18n').t(key),
        getLang: () => (Alpine.store('i18n').current === 'en' ? 'en' : 'pt'),
        setLang: (lang) => Alpine.store('i18n').set(lang === 'en' ? 'en' : 'pt-BR'),
    };
});
